// Вывод приветствия
alert("Добро пожаловать в программу!");

// Ввод имени пользователя
let name = prompt("Введите ваше имя:");

// Проверяем, ввёл ли пользователь имя
if (name === null || name === "") {
    alert("Имя не было введено.");
}
else {

    // Подтверждение введённых данных
    let answer = confirm(
        "Вы ввели имя: " + name + "\nПодтвердить?"
    );

    if (answer) {
        alert("Здравствуйте, " + name + "!");
    }
    else {

        // Повторный ввод имени
        let newName = prompt("Введите имя ещё раз:");

        if (newName !== null && newName !== "") {
            alert("Здравствуйте, " + newName + "!");
        }
        else {
            alert("Имя не указано.");
        }
    }
}